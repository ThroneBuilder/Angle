// Generates src/geometry/trig-table.ts: cos and sin for every tenth of a degree, 0–90°.
// The solver uses only this table (never Math.sin/Math.cos), so results are identical in every
// JavaScript engine (research R2). Run with `pnpm gen:trig` and commit the output.
import { writeFileSync } from 'node:fs';

const N = 900;
const cos: number[] = [];
const sin: number[] = [];
for (let k = 0; k <= N; k++) {
  const r = (k * Math.PI) / 1800;
  cos.push(Math.cos(r));
  sin.push(Math.sin(r));
}
// Exact endpoints, and exact symmetry so cos(k) === sin(900 - k).
cos[0] = 1;
sin[0] = 0;
cos[N] = 0;
sin[N] = 1;
for (let k = 0; k <= N; k++) {
  if (k > N / 2) cos[k] = sin[N - k]!;
}
for (let k = 0; k <= N; k++) {
  sin[k] = cos[N - k]!;
}

const fmt = (values: number[]) =>
  values.map((v, k) => `  ${v.toString()}, // ${k}`).join('\n');

const out = `// GENERATED by scripts/gen-trig-table.ts. Do not edit by hand.
// cos and sin of k tenths of a degree, k = 0…900, as exact double literals (research R2).

export const COS: readonly number[] = [
${fmt(cos)}
];

export const SIN: readonly number[] = [
${fmt(sin)}
];
`;

writeFileSync(new URL('../src/geometry/trig-table.ts', import.meta.url), out);
console.log('Wrote src/geometry/trig-table.ts');
